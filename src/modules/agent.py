def indentify_themes(text: str, themes_list: list[str]) -> list[str] | None:
    themes = ""
    for theme in themes_list:
        themes += theme + ', /n'

    prompt = (f"""
        Вот текст заметки, он попадет в мое хранилище заметок:

        <note_text>
        {text}
        </note_text>

        Определи темы, которые упоминаются в этой заметке.

        Обращай внимание как на общие темы (например: свобода, английское средневековье, математика и т.д.), так и на конкретные (например: прочитанные книги, термины и т.д.)

        Важно: эти темы используются для связи с другими заметками, поэтому темы должны быть конкретными.
        Например: не стоит указывать тему самочуствие, нужно указать хорошее самочуствие или плохое самочуствие, иначе заметки с хорошим и плохим самочуствием перемешаются.
        Также не стоит указывать пустые темы, я использую обсидиан для объединения мыслей и синтеза новых, например тема "хорошая погода", не поможет понять мне нечто новое и просто создаст путаницу, таких тем стоит избегать.
        Тему стоит указывать только если размышления на эту тему могут действительно представлять какую-то ценность, если что-то просто упоминается, не стоит указывать тему для этого.
        Название темы не должно содержать более двух слов, лучше одно.

        Если в тексте есть определение, оно тоже должно быть включено в темы, например "Большой Другой" у Лакана.

        Если не видишь стоящих тем в тексте, просто не указывай ничего.

        Вот темы которые уже есть, если среди них есть подходящие - используй их (также можешь использовать их как примеры):
        <themes>
        {themes}
        </themes>

        Если существующих тем достаточно, новую создавать не надо.

        Если среди готовых тем нет подходящей укажи новую.

        Помести каждую тему которую ты определишь в XML тэг <theme>
    """)
    result = agent.invoke(
            {"messages": [{"role": "user", "content": prompt}]}
        )

    print(result["messages"][-1].content)

    return find_themes(result["messages"][-1].content)

