from langchain_ollama import ChatOllama
from langchain.agents import create_agent
import re


def find_type(text: str) -> str | None:
    """
    Находит первое вхождение текста внутри тегов <type>...</type>.

    :param text: Исходная строка для поиска
    :return: Содержимое первого тега <type> или None, если тег не найден
    """
    match = re.search(r'<type>(.*?)</type>', text, re.DOTALL)
    return match.group(1) if match else None

def find_themes(text: str) -> list[str] | None:
    """
    Находит все вхождения текста внутри тегов <theme>...</theme>.

    :param text: Исходная строка для поиска
    :return: Содержимое тегов <theme> или None, если тег не найден
    """
    return re.findall(r'<theme>(.*?)</theme>', text, re.DOTALL)

